import os

# Версия сборки. Её «вшивает» в образ стадия сборки (V фактор):
#   docker build --build-arg APP_VERSION=2.2.0 …  →  ENV APP_VERSION в образе
# (см. Dockerfile). Так из одного исходника получаются образы разных версий, а
# по ответу, логу или метрике видно, какая версия обработала запрос (ДЗ №8).
# Без переменной (локальный запуск, тесты) — версия исходников.
__version__ = os.environ.get("APP_VERSION") or "2.1.0"
